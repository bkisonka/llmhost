// Контур качества: качество как координата
// петли самоизмерения — по той же дисциплине, что скорость (note_speed в
// форме, гейт вердикта сетки). Фиксированный каталог задач, детерминизм
// обеспечивает сам суит: temperature/seed в запросах, проверка ответа —
// детерминированная, без исполнения кода демоном. Демон не решает задачи —
// он замеряет, умеет ли модель решать их на этой форме.
//
// Граница клиент/хост (план): дешёвые детерминированные проверки ЭТОГО суита
// — часть хоста (метрика петли); полноценная верификация шагов агента —
// клиентская зона, хост её не оркестрирует и не видит.
#pragma once
#include <cstdint>
#include <string>

namespace lh::quality {

// Скор по метрике: 0..1; <0 — «нет» (задача не снялась — движок отказал,
// таймаут). Пустота ≠ провал: гейты пустоту не считают регрессом.
struct Scores {
  double needle = -1; // извлечение: needle-recall на контексте замера
  double tools = -1;  // корректность tool-call на небольшой схеме
  double code = -1;   // детерминированная задача с проверкой ответа по числу
  double agree = -1;  // согласие резидентов (заполняет run_agreement);
                      // без назначенного верификатора метрика честно «нет»
  int tasks = 0;      // сколько задач реально снялось
};

// Прогон суита на ребёнке (порт/ключ — фактический спавн кандидата).
// ctx — фактический контекст замера: needle строится от него (с потолком,
// см. quality.cpp — задача суита различать формы одной модели, а не мерить
// абсолютную глубину). false — err объясняет (ребёнок не отвечает и т.п.);
// отдельные задачи могут не сняться — их скоры остаются «нет».
// Ребёнок одно-модельный: поле «model» ему не пересылается (пин на чужой id
// отвечает пустым телом — проверено на стенде).
bool run_suite(int port, const std::string& key, uint32_t ctx, Scores& out,
               std::string& err);

// Согласие резидентов — четвёртая метрика: одна задача worker'у и
// верификатору (два живых ребёнка); расхождение ответов — сигнал ошибки
// рассуждения, который needle и tool-call не ловят (внешняя проверка ловит
// извлечение, согласие — вывод). score = 1 (совпали) / 0 (разошлись);
// «нет» — кто-то из детей не ответил.
bool run_agreement(int worker_port, const std::string& worker_key,
                   int verifier_port, const std::string& verifier_key,
                   double& score, std::string& err);

} // namespace lh::quality
