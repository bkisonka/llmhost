// MTP-модули — родные ускорители спекулятивного декодирования, обученные
// вместе с моделью (замер на этой сборке: gemma-4-12b + её модуль = +27%).
// После загрузки основной модели модуль ищется в реестре рядом или в каталоге,
// скорость замеряется на машине пользователя и предлагается включение.
// Решение помнится в state.json (mtp_choices), включение — через llmhost.conf
// (тот же механизм, что и ручное, — можно отменить, убрав запись).
#pragma once
#include <cstdint>
#include <string>

namespace lh::mtp {

struct Module {
  std::string path;      // целевой путь файла (есть или будет после докачки)
  std::string repo;       // "org/repo" для докачки
  std::string file;       // путь в репозитории ("MTP/mtp-....gguf")
  std::string stem;       // имя без расширения — значение «model-draft»
  uint64_t size = 0;
  bool downloaded = false;
};

// Найти MTP-модуль к основной модели: сначала реестр (уже скачан рядом),
// затем каталог (сетевой запрос с кэшем; оффлайн — просто не найдём). false — нет.
bool find_module(const std::string& main_path, Module& out, std::string& err);

// После успешной загрузки модели (из рабочего потока UI-загрузки): замерить
// скорость, при первом знакомстве спросить про MTP и включить по согласию.
// Молчит, когда решать нечего: классический режим, модуля нет, уже спрашивали
// или черновик уже настроен.
void after_load(const std::string& main_path);

} // namespace lh::mtp
